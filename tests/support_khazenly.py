"""A synthetic Khazenly *Dashboard - Active Orders* export (ADR 0071).

Laid out as Khazenly's real export is - one sheet, a title and filter lines
above the header, columns B to N, Account and status filled on the first row
only, Subtotal / Total / Count footers, and every cell an inline string - but
every order number and name is made up. **A real export holds customer names
and is never copied into the repository.**

``python tests/support_khazenly.py out.xlsx 31840 31841 …`` writes one for a
browser check.
"""

import io
import sys
import zipfile
from xml.sax.saxutils import escape

HEADER = [
    None,
    "Account  ↑",
    "Order Status (Summarized)  ↑",
    None,
    "Sales Order: Sales Order Number",
    "Merchant Order Number",
    "Recipient Name",
    "Sales Invoice Amount",
    "Planned COD Amount",
    "Shipping Fees",
    "Order Status",
    "Order Status Date",
    "Sales Order: Created Date",
    "On Hold Reason",
]

FILTERS = [
    "Show: All sales orders",
    "Order Status equals New Order,Order On Hold,Order Ready",
    "Sales Order: Record Type equals Sales Order,Sales Order ReadOnly",
    "Courrier equals Picked by Merchant",
    "Order Status (Summarized) equals On Hold",
]

COLUMNS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"


def order_row(sales_order: str, merchant_order, first: bool = False) -> list:
    return [
        None,
        "HBA" if first else None,
        "On Hold" if first else None,
        None,
        sales_order,
        merchant_order,
        "Test Customer",
        815.0,
        815.0,
        77.52,
        "Order On Hold",
        "29/10/2026, 21:16",
        "29/10/2026",
        "Pending Confirmation",
    ]


def footer(count: int) -> list[list]:
    return [
        [None, None, "Subtotal", "Sum", None, None, None, 815.0, 815.0, 77.52],
        [None, None, None, "Count", float(count)],
        [None, "Subtotal", None, "Sum", None, None, None, 815.0, 815.0, 77.52],
        [None, None, None, "Count", float(count)],
        [None, "Total", None, "Sum", None, None, None, 815.0, 815.0, 77.52],
        [None, None, None, "Count", float(count)],
    ]


def rows_for(orders: list[tuple[str, object]], filters: list[str] | None = None, count: int | None = None) -> list[list]:
    """The sheet's rows: title, filter lines, header, orders, footer."""
    filters = FILTERS if filters is None else filters
    rows: list[list] = [
        [],
        [None, "Dashboard - Active Orders"],
        [None, "As of 2026-10-30 22:45:38 Eastern European Time/EET • Generated by Test"],
        [],
        [],
        [None, "Filtered By"],
        *[[None, line] for line in filters],
        [],
        HEADER,
    ]
    rows += [order_row(sales, merchant, first=index == 0) for index, (sales, merchant) in enumerate(orders)]
    rows += footer(len(orders) if count is None else count)
    return rows


def _cell(ref: str, value) -> str:
    if value is None:
        return ""
    if isinstance(value, (int, float)):
        return f'<c r="{ref}" t="n"><v>{value}</v></c>'
    return f'<c r="{ref}" t="inlineStr"><is><t>{escape(str(value))}</t></is></c>'


def workbook(rows: list[list], sheet_name: str = "Dashboard - Active Orders") -> bytes:
    """An .xlsx holding ``rows`` with inline strings and no shared strings."""
    sheet_rows = "".join(
        f'<row r="{number}">' + "".join(_cell(f"{COLUMNS[col]}{number}", value) for col, value in enumerate(row)) + "</row>"
        for number, row in enumerate(rows, start=1)
    )
    main = "http://schemas.openxmlformats.org/spreadsheetml/2006/main"
    rel = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"
    parts = {
        "[Content_Types].xml": (
            '<?xml version="1.0" encoding="UTF-8"?>'
            '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
            '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
            '<Default Extension="xml" ContentType="application/xml"/>'
            '<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>'
            '<Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>'
            '<Override PartName="/xl/sharedStrings.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sharedStrings+xml"/>'
            "</Types>"
        ),
        "_rels/.rels": (
            '<?xml version="1.0" encoding="UTF-8"?>'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>'
            "</Relationships>"
        ),
        "xl/workbook.xml": (
            f'<?xml version="1.0" encoding="UTF-8"?><workbook xmlns="{main}" xmlns:r="{rel}">'
            f'<sheets><sheet name="{escape(sheet_name)}" sheetId="1" r:id="rId3"/></sheets></workbook>'
        ),
        "xl/_rels/workbook.xml.rels": (
            '<?xml version="1.0" encoding="UTF-8"?>'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId3" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>'
            '<Relationship Id="rId4" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/sharedStrings" Target="sharedStrings.xml"/>'
            "</Relationships>"
        ),
        "xl/sharedStrings.xml": f'<?xml version="1.0" encoding="UTF-8"?><sst count="0" uniqueCount="0" xmlns="{main}"/>',
        "xl/worksheets/sheet1.xml": (
            f'<?xml version="1.0" encoding="UTF-8"?><worksheet xmlns="{main}"><sheetData>{sheet_rows}</sheetData></worksheet>'
        ),
    }
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as package:
        for name, text in parts.items():
            package.writestr(name, text.encode("utf-8"))
    return buffer.getvalue()


def export(orders: list[tuple[str, object]], **kwargs) -> bytes:
    """An export listing ``orders`` as (sales order number, merchant order number)."""
    return workbook(rows_for(orders, **kwargs))


if __name__ == "__main__":
    out, *numbers = sys.argv[1:]
    with open(out, "wb") as handle:
        handle.write(export([(f"KH-HBA-{9_000_000 + i:08d}", number) for i, number in enumerate(numbers)]))
